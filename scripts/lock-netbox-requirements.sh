# Lock the Python requirements of one NetBox release for the docs build: each version with its hashes.
# Usage: scripts/lock-netbox-requirements.sh <NetBox tag> <Python version>, the values in docs-build.yaml.
set -euo pipefail

usage="usage: $0 <NetBox tag, for example v4.7.0> <Python version, for example 3.14>"
tag=${1:?$usage}
python=${2:?$usage}
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

curl --proto =https --fail --silent --show-error --location --output "$work/requirements.txt" \
  "https://raw.githubusercontent.com/netbox-community/netbox/$tag/requirements.txt"
# psycopg-binary replaces the C build of psycopg; promise publishes no wheel, so it is the one source build.
sed -n '/^psycopg\[/{s/\bc\b/binary/;p}' "$work/requirements.txt" > "$work/overrides.txt"
grep --quiet 'binary' "$work/overrides.txt" || { echo "$tag: no psycopg[c] requirement to replace" >&2; exit 1; }

{
  echo "# NetBox $tag on Python $python: generated by scripts/lock-netbox-requirements.sh"
  uv pip compile --system-certs --quiet --no-header --no-annotate --generate-hashes \
    --python-version "$python" --python-platform x86_64-unknown-linux-gnu \
    --only-binary=:all: --no-binary=promise --override "$work/overrides.txt" "$work/requirements.txt"
} > "$work/netbox-requirements.txt"
mv "$work/netbox-requirements.txt" .github/netbox-requirements.txt
